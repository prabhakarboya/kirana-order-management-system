-- 100% Native MySQL DDL: Tables, Foreign Keys, Unique Keys, Indexes, Constraints

CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(191) PRIMARY KEY,
  phone VARCHAR(191) NOT NULL UNIQUE,
  role VARCHAR(50) NOT NULL DEFAULT 'RETAILER',
  name VARCHAR(191) NOT NULL,
  otpCode VARCHAR(20) NULL,
  otpExpiresAt DATETIME(3) NULL,
  otpAttempts INT NOT NULL DEFAULT 0,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX idx_users_phone (phone)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS brands (
  id VARCHAR(191) PRIMARY KEY,
  code VARCHAR(191) NOT NULL UNIQUE,
  name VARCHAR(191) NOT NULL,
  description TEXT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS categories (
  id VARCHAR(191) PRIMARY KEY,
  name VARCHAR(191) NOT NULL UNIQUE,
  description TEXT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS salesmen (
  id VARCHAR(191) PRIMARY KEY,
  userId VARCHAR(191) NULL UNIQUE,
  name VARCHAR(191) NOT NULL,
  phone VARCHAR(191) NOT NULL UNIQUE,
  territory VARCHAR(191) NOT NULL DEFAULT 'Jabalpur City',
  isActive BOOLEAN NOT NULL DEFAULT TRUE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS retailers (
  id VARCHAR(191) PRIMARY KEY,
  userId VARCHAR(191) NOT NULL UNIQUE,
  shopName VARCHAR(191) NOT NULL,
  ownerName VARCHAR(191) NOT NULL,
  phone VARCHAR(191) NOT NULL,
  address VARCHAR(255) NOT NULL,
  creditLimit DOUBLE NOT NULL DEFAULT 50000.0,
  creditUsed DOUBLE NOT NULL DEFAULT 0.0,
  lastOrderAt DATETIME(3) NULL,
  salesmanName VARCHAR(191) NULL DEFAULT 'Rajesh Sharma',
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE,
  INDEX idx_retailers_phone (phone),
  INDEX idx_retailers_last_order (lastOrderAt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS retailer_salesman_assignments (
  id VARCHAR(191) PRIMARY KEY,
  retailerId VARCHAR(191) NOT NULL,
  salesmanId VARCHAR(191) NOT NULL,
  isPrimary BOOLEAN NOT NULL DEFAULT TRUE,
  assignedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (retailerId) REFERENCES retailers(id) ON DELETE CASCADE,
  FOREIGN KEY (salesmanId) REFERENCES salesmen(id) ON DELETE CASCADE,
  UNIQUE KEY uk_ret_sm (retailerId, salesmanId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS credit_accounts (
  id VARCHAR(191) PRIMARY KEY,
  retailerId VARCHAR(191) NOT NULL UNIQUE,
  creditLimit DOUBLE NOT NULL DEFAULT 50000.0,
  creditUsed DOUBLE NOT NULL DEFAULT 0.0,
  creditAvailable DOUBLE NOT NULL DEFAULT 50000.0,
  status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
  paymentTermsDays INT NOT NULL DEFAULT 7,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (retailerId) REFERENCES retailers(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS skus (
  code VARCHAR(191) PRIMARY KEY,
  name VARCHAR(191) NOT NULL,
  brand VARCHAR(191) NOT NULL,
  category VARCHAR(191) NOT NULL,
  unitLabel VARCHAR(191) NOT NULL,
  piecesPerCase INT NOT NULL DEFAULT 1,
  dealerPrice DOUBLE NOT NULL,
  casePrice DOUBLE NOT NULL,
  gstIncluded BOOLEAN NOT NULL DEFAULT FALSE,
  gstRate DOUBLE NOT NULL DEFAULT 18.0,
  stockCases INT NOT NULL DEFAULT 0,
  imageUrl VARCHAR(500) NULL,
  isActive BOOLEAN NOT NULL DEFAULT TRUE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX idx_skus_brand (brand),
  INDEX idx_skus_category (category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS product_images (
  id VARCHAR(191) PRIMARY KEY,
  skuCode VARCHAR(191) NOT NULL,
  imageUrl VARCHAR(500) NOT NULL,
  isPrimary BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (skuCode) REFERENCES skus(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS retailer_prices (
  id VARCHAR(191) PRIMARY KEY,
  retailerId VARCHAR(191) NOT NULL,
  skuCode VARCHAR(191) NOT NULL,
  dealerPrice DOUBLE NOT NULL,
  casePrice DOUBLE NOT NULL,
  FOREIGN KEY (retailerId) REFERENCES retailers(id) ON DELETE CASCADE,
  FOREIGN KEY (skuCode) REFERENCES skus(code) ON DELETE CASCADE,
  UNIQUE KEY uk_ret_sku (retailerId, skuCode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS schemes (
  id VARCHAR(191) PRIMARY KEY,
  skuCode VARCHAR(191) NOT NULL,
  type VARCHAR(50) NOT NULL,
  title VARCHAR(191) NOT NULL,
  description TEXT NOT NULL,
  configJson TEXT NOT NULL,
  isActive BOOLEAN NOT NULL DEFAULT TRUE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (skuCode) REFERENCES skus(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS scheme_rules (
  id VARCHAR(191) PRIMARY KEY,
  schemeId VARCHAR(191) NOT NULL,
  ruleType VARCHAR(50) NOT NULL,
  minQty INT NOT NULL DEFAULT 0,
  discountPercent DOUBLE NOT NULL DEFAULT 0.0,
  freeSkuCode VARCHAR(191) NULL,
  freeQty INT NOT NULL DEFAULT 0,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (schemeId) REFERENCES schemes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS orders (
  id VARCHAR(191) PRIMARY KEY,
  orderNumber VARCHAR(191) NOT NULL UNIQUE,
  clientOrderId VARCHAR(191) NULL UNIQUE,
  retailerId VARCHAR(191) NOT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'PENDING_DESK_REVIEW',
  source VARCHAR(50) NOT NULL DEFAULT 'APP',
  rawMessage TEXT NULL,
  subtotal DOUBLE NOT NULL,
  discountTotal DOUBLE NOT NULL DEFAULT 0.0,
  gstTotal DOUBLE NOT NULL,
  grandTotal DOUBLE NOT NULL,
  totalSavings DOUBLE NOT NULL DEFAULT 0.0,
  creditApproved BOOLEAN NOT NULL DEFAULT TRUE,
  stockDeducted BOOLEAN NOT NULL DEFAULT FALSE,
  rejectionReason TEXT NULL,
  tallyExported BOOLEAN NOT NULL DEFAULT FALSE,
  tallyVoucherNo VARCHAR(191) NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (retailerId) REFERENCES retailers(id) ON DELETE RESTRICT,
  INDEX idx_orders_status (status),
  INDEX idx_orders_retailer (retailerId),
  INDEX idx_orders_created (createdAt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS order_lines (
  id VARCHAR(191) PRIMARY KEY,
  orderId VARCHAR(191) NOT NULL,
  skuCode VARCHAR(191) NOT NULL,
  qtyCases INT NOT NULL,
  freeCases INT NOT NULL DEFAULT 0,
  unitPrice DOUBLE NOT NULL,
  discountAmount DOUBLE NOT NULL DEFAULT 0.0,
  gstRate DOUBLE NOT NULL,
  gstAmount DOUBLE NOT NULL,
  lineTotal DOUBLE NOT NULL,
  schemeApplied VARCHAR(255) NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE CASCADE,
  FOREIGN KEY (skuCode) REFERENCES skus(code) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS order_status_history (
  id VARCHAR(191) PRIMARY KEY,
  orderId VARCHAR(191) NOT NULL,
  statusFrom VARCHAR(50) NOT NULL,
  statusTo VARCHAR(50) NOT NULL,
  changedByUserId VARCHAR(191) NULL,
  changedByName VARCHAR(191) NOT NULL DEFAULT 'System',
  reason TEXT NULL,
  timestamp DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS aliases (
  id VARCHAR(191) PRIMARY KEY,
  retailerId VARCHAR(191) NULL,
  phrase VARCHAR(191) NOT NULL,
  skuCode VARCHAR(191) NOT NULL,
  confidence DOUBLE NOT NULL DEFAULT 1.0,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (retailerId) REFERENCES retailers(id) ON DELETE CASCADE,
  FOREIGN KEY (skuCode) REFERENCES skus(code) ON DELETE CASCADE,
  INDEX idx_aliases_phrase (phrase),
  INDEX idx_aliases_ret_phrase (retailerId, phrase)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS audit_logs (
  id VARCHAR(191) PRIMARY KEY,
  orderId VARCHAR(191) NULL,
  userId VARCHAR(191) NULL,
  userName VARCHAR(191) NOT NULL,
  action VARCHAR(100) NOT NULL,
  details TEXT NULL,
  timestamp DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE SET NULL,
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE SET NULL,
  INDEX idx_audit_order (orderId),
  INDEX idx_audit_timestamp (timestamp)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ai_order_capture_records (
  id VARCHAR(191) PRIMARY KEY,
  retailerId VARCHAR(191) NULL,
  channel VARCHAR(50) NOT NULL,
  rawInput TEXT NOT NULL,
  parsedOutputJson TEXT NOT NULL,
  confidenceScore DOUBLE NOT NULL DEFAULT 0.0,
  reviewStatus VARCHAR(50) NOT NULL DEFAULT 'REVIEWED',
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (retailerId) REFERENCES retailers(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS export_history (
  id VARCHAR(191) PRIMARY KEY,
  exportFormat VARCHAR(50) NOT NULL,
  voucherCount INT NOT NULL,
  fileName VARCHAR(255) NOT NULL,
  exportedByUserId VARCHAR(191) NULL,
  checksum VARCHAR(191) NULL,
  generatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS offline_sync_queue (
  id VARCHAR(191) PRIMARY KEY,
  clientOrderId VARCHAR(191) NOT NULL UNIQUE,
  salesmanId VARCHAR(191) NULL,
  payloadJson TEXT NOT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'SYNCED',
  syncAttempts INT NOT NULL DEFAULT 1,
  errorDetails TEXT NULL,
  syncedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
